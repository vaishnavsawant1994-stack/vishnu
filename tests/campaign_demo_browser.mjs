import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const browser = await chromium.launch({ headless: true, executablePath: process.env.CHAT_TEST_CHROMIUM_PATH || undefined });
const fixture = await readFile(new URL('../pwa/campaign-demo-data.js', import.meta.url), 'utf8');
const script = await readFile(new URL('../pwa/campaign-demo.js', import.meta.url), 'utf8');
const style = await readFile(new URL('../pwa/campaign-demo.css', import.meta.url), 'utf8');
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.route('**/iphone/api/**', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }));
  await page.route('**/iphone/campaign-demo.css', route => route.fulfill({ status: 200, contentType: 'text/css', body: style }));
  await page.goto('http://127.0.0.1:4173/iphone/?campaignDemo=1', { waitUntil: 'domcontentloaded' });
  await page.addScriptTag({ content: fixture });
  await page.addScriptTag({ content: script });
  await page.locator('#vishnuCampaignDemo .vd-demo-banner').waitFor();
  await mkdir('artifacts/campaign-demo', { recursive: true });
  assert.match(await page.locator('#vishnuCampaignDemo').innerText(), /Rudra Health Care/);
  assert.match(await page.locator('#vishnuCampaignDemo').innerText(), /Patient CRM/);
  assert.equal(await page.locator('.vd-home-hero .vd-core img').evaluate(image => image.complete && image.naturalWidth > 0), true, 'canonical Vishnu Core asset must load');
  await page.screenshot({ path: 'artifacts/campaign-demo/home-desktop.png', fullPage: false });
  await page.locator('[data-project]').first().click();
  await page.getByRole('heading', { name: 'Patient CRM implementation' }).waitFor();
  await page.screenshot({ path: 'artifacts/campaign-demo/conversation-desktop.png' });
  await page.locator('[data-nav="work"]').first().click();
  await page.getByRole('heading', { name: 'Conversation History' }).waitFor();
  await page.screenshot({ path: 'artifacts/campaign-demo/history-desktop.png' });
  await page.locator('[data-open-search]').focus();
  await page.getByRole('heading', { name: 'Global Search' }).waitFor();
  await page.screenshot({ path: 'artifacts/campaign-demo/search-desktop.png' });
  await page.locator('[data-nav="home"]').first().click();
  await page.locator('[data-nav="voice"]').first().click();
  await page.getByRole('heading', { name: 'Voice / Live Conversation' }).waitFor();
  await page.screenshot({ path: 'artifacts/campaign-demo/voice-desktop.png' });
  await page.getByRole('button', { name: 'Mute', exact: true }).click();
  assert.match(await page.locator('.vd-sensor-notice').innerText(), /No microphone/);
  const requestMethods = [];
  page.on('request', request => { if (request.url().includes('/iphone/api/')) requestMethods.push(request.method()); });
  await page.locator('[data-nav="home"]').first().click();
  await page.locator('[data-composer] input').fill('Local test message');
  await page.locator('[data-composer] .vd-send').click();
  await page.getByText('Local test message').waitFor();
  assert.equal(requestMethods.some(method => !['GET', 'HEAD'].includes(method)), false, 'sample message must not issue a write API request');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(150);
  await page.locator('.vd-bottom-nav [data-nav="home"]').click();
  await page.waitForTimeout(250);
  await page.screenshot({ path: 'artifacts/campaign-demo/home-mobile.png', fullPage: false });
  const checkMobile = async name => {
    const bounds = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, inner: innerWidth, nav: getComputedStyle(document.querySelector('.vd-bottom-nav')).display }));
    assert.ok(bounds.width <= bounds.inner, `${name} mobile preview overflows viewport: ${JSON.stringify(bounds)}`);
    assert.equal(bounds.nav, 'grid', `${name} mobile preview lost bottom navigation`);
    await page.screenshot({ path: `artifacts/campaign-demo/${name}-mobile.png`, fullPage: false });
  };
  await checkMobile('home');
  await page.locator('[data-project]').first().click();
  await page.getByRole('heading', { name: 'Patient CRM implementation' }).waitFor();
  await checkMobile('conversation');
  await page.locator('.vd-bottom-nav [data-nav="work"]').click();
  await page.getByRole('heading', { name: 'Conversation History' }).waitFor();
  await checkMobile('history');
  await page.locator('.vd-bottom-nav [data-nav="more"]').click();
  await page.locator('.vd-more-sheet [data-nav="search"]').click();
  await page.getByRole('heading', { name: 'Global Search' }).waitFor();
  await checkMobile('search');
  await page.locator('.vd-bottom-nav [data-nav="home"]').click();
  await page.locator('.vd-composer [data-nav="voice"]').click();
  await page.getByRole('heading', { name: 'Voice / Live Conversation' }).waitFor();
  await checkMobile('voice');
  assert.deepEqual(errors, []);
  console.log('Campaign demo browser test passed: all five previews, isolated sample compose, voice-safety notice, and mobile navigation/overflow.');
} finally {
  await browser.close();
}
